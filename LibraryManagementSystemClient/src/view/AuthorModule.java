    private void addColumnToTable(){
        tableModel.addColumn("ID");
        tableModel.addColumn("NAMES");
        tableModel.addColumn("NATIONAL ID");
        tableModel.addColumn("BIO");
        // change the table model of author to refer on this
        authorTable.setModel(tableModel);
    }
    
    private void addRowsDataToTable(){
        try{
            tableModel.setRowCount(0);
            Registry theRegistry = LocateRegistry.getRegistry("127.0.0.1", 8002);
            AuthorService service = (AuthorService)theRegistry.lookup("author-service");
            List<Author> authors = service.findAllAuthorRecords();
            for(Author author : authors){
                tableModel.addRow(new Object[]{
                    author.getId(),
                    author.getNames(),
                    author.getNationalId(),
                    author.getBio()
                });
            }
        }catch(Exception ex){
            ex.printStackTrace();
        }
    }
    
