    private void registerBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerBtnActionPerformed
        // validation 
        try{
            // grab the user input and send to model
            Author authorObj = new Author();
            authorObj.setBio(bioTxt.getText());
            authorObj.setNames(namesTxt.getText());
            authorObj.setNationalId(nationalIdTxt.getText());
            // we need to invoke method on server side
            Registry theRegistry = LocateRegistry.getRegistry("127.0.0.1", 8002);
            AuthorService service = (AuthorService)theRegistry.lookup("author-service");
            Author savedObj = service.registerAuthorRecord(authorObj);
            if(Objects.isNull(savedObj)){
                JOptionPane.showMessageDialog(this, "Data Not Saved");
            }else{
                JOptionPane.showMessageDialog(this, "Data Saved Successful");
            }
            addRowsDataToTable();
            
        }catch(Exception ex){
            ex.printStackTrace();
        }
    }//GEN-LAST:event_registerBtnActionPerformed

