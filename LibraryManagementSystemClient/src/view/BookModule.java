    private void registerBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerBtnActionPerformed
        // validation
        try{
            Registry theRegistry = LocateRegistry.getRegistry("127.0.0.1", 8002);
            // grab the user input and send to model
            Book bookObj = new Book();
            bookObj.setTitle(titleTxt.getText());
            bookObj.setISBN(isbnTxt.getText());
            Date publishedDate = publishDateChoosed.getDate();
            LocalDate convertedDate = publishedDate
                    .toInstant().atZone(ZoneId.systemDefault())
                    .toLocalDate();
            bookObj.setPublishedDate(convertedDate);
            
            List<Author> authors = authorList.getSelectedValuesList();
            bookObj.setAuthors(new HashSet<>(authors));
            // create barcode from server side
            BarcodeService barcodeService = (BarcodeService) theRegistry.lookup("barcode-service");
            Barcode theBarcode = barcodeService.getNextBarcode();
            bookObj.setBarcode(theBarcode);
            
            BookService bookService = (BookService) theRegistry.lookup("book-service");
            Book savedObj = bookService.registerBookRecord(bookObj);
            if(Objects.nonNull(savedObj)){
                JOptionPane.showMessageDialog(this, "Data saved!");
            }else{
                JOptionPane.showMessageDialog(this, "Data Not Saved!");
            }
            
            addRowDataToTable();
            
        }catch(Exception ex){
            ex.printStackTrace();
        }
    }//GEN-LAST:event_registerBtnActionPerformed

