    private void addColumnsToTable(){
        tableModel.addColumn("Title");
        tableModel.addColumn("ISBN");
        tableModel.addColumn("Publishing Date");
        tableModel.addColumn("Barcode");
        tableModel.addColumn("Author");
        bookTable.setModel(tableModel);
    }
    
    private void addRowDataToTable(){
        try{
            tableModel.setRowCount(0);
            Registry theRegistry = LocateRegistry.getRegistry("127.0.0.1", 8002);
            BookService service = (BookService) theRegistry.lookup("book-service");
            List<Book> books = service.findAllBookRecords();
            for(Book theBook : books){
                tableModel.addRow(new Object[]{
                    theBook.getTitle(),
                    theBook.getISBN(),
                    theBook.getPublishedDate(),
                    theBook.getBarcode(),
                    theBook.getAuthors(),
                });
            }
        }catch(Exception ex){
            ex.printStackTrace();
        }
    }
    
    private void addAuthorToList(){
        try{
            Registry theRegistry = LocateRegistry.getRegistry("127.0.0.1", 8002);
            AuthorService service = (AuthorService) theRegistry.lookup("author-service");
            List<Author> authors = service.findAllAuthorRecords();
            for(Author theAuthor : authors){
                listModel.addElement(theAuthor);
            }
            
            authorList.setModel(listModel);
        }catch(Exception ex){
            ex.printStackTrace();
        }
    }
    
